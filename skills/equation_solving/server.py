    from sympy.solvers.solvers import solve
    from sympy.core.sympify import sympify
    if not isinstance(equations, str) or not equations.strip():
        raise ValueError('equations must be a non-empty string')
    if not isinstance(variables, str) or not variables.strip():
        raise ValueError('variables must be a non-empty string')

