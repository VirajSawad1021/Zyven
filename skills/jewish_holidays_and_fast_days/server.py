def get_shabbat_for_date(date: Annotated[str, Field(description="Gregorian civil date in YYYY-MM-DD format.")]) -> dict[str, Any]:
    """Find the Shabbat on or following a Gregorian date, including how many days away it is.

    date: Gregorian civil date in YYYY-MM-DD format.

    Returns: date (string): The queried Gregorian date in YYYY-MM-DD format., shabbat_date (string): Gregorian date of the Shabbat on or following the queried date, in YYYY-MM-DD format., is_shabbat (boolean): True if the queried date itself is Shabbat., days_until_shabbat (integer): Number of days from the queried date to that Shabbat, where 0 means the queried date is Shabbat.
    """
    from pyluach.dates import GregorianDate
    try:
        date
    except NameError:
        date = None

    if not isinstance(date, str):
        raise ValueError("date must be a string in YYYY-MM-DD format")
    date = date.strip()
    parts = date.split("-")
    if len(parts) != 3 or not (len(parts[0]) == 4 and len(parts[1]) == 2 and len(parts[2]) == 2):
        raise ValueError("date must be in YYYY-MM-DD format")
    try:
        year, month, day = (int(part) for part in parts)
    except ValueError as exc:
        raise ValueError("date must contain integer year, month, and day") from exc

    try:
        date_obj = GregorianDate(year, month, day)
    except Exception as exc:
        raise ValueError(f"invalid Gregorian date: {date}") from exc

    shabbat_obj = date_obj.shabbos()
    shabbat_date = f"{shabbat_obj.year:04d}-{shabbat_obj.month:02d}-{shabbat_obj.day:02d}"
    days_until_shabbat = int(shabbat_obj - date_obj)

    return {
        "date": date,
        "shabbat_date": shabbat_date,
        "is_shabbat": days_until_shabbat == 0,
        "days_until_shabbat": days_until_shabbat,
    }

