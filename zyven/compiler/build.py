"""Assemble a generated MCP server from a CapabilitySpec + model-written tool bodies.

The model only writes function bodies and import lines. Everything structural (server object,
signatures, types, decorators, docstrings) is generated deterministically here, then checked by
`policy.check_adapter` before anything is executed.
"""

from __future__ import annotations

import json
import textwrap

from zyven.ai.schemas import AdapterCode, CapabilitySpec, ToolImpl, ToolSpec

PY_TYPES = {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "array": "list", "object": "dict"}


def signature_line(tool: ToolSpec) -> str:
    required = [p for p in tool.params if p.required]
    optional = [p for p in tool.params if not p.required]
    parts = [f"{p.name}: {PY_TYPES[p.type]}" for p in required]
    parts += [f"{p.name}: {PY_TYPES[p.type]} | None = None" for p in optional]
    return f"def {tool.name}({', '.join(parts)}) -> dict[str, Any]:"


def docstring(tool: ToolSpec) -> str:
    lines = [tool.description, ""]
    lines += [f"{p.name}: {p.description}" for p in tool.params]
    lines += ["", "Returns: " + ", ".join(f"{r.name} ({r.type}): {r.description}" for r in tool.returns)]
    text = "\n".join(lines).replace('"""', "'''")
    return textwrap.indent(f'"""{text}\n"""', "    ")


def assemble(spec: CapabilitySpec, code: AdapterCode, provenance: dict) -> str:
    impls = {i.tool: i for i in code.tools}
    # Each tool's imports are placed inside its own function: two tools importing different functions
    # with the same name (e.g. luhn.checksum vs verhoeff.checksum) can never shadow each other.
    imports: list[str] = []
    header = [
        f'"""Zyven-generated MCP server: {spec.title}.',
        "",
        f"Source: {provenance.get('repository')} @ {provenance.get('commit')} ({provenance.get('license')})",
        f"Generated by: {provenance.get('generator')} with model {provenance.get('model')}",
        "Model-written code is limited to tool bodies and imports; the harness writes the rest.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any",
        "",
        "from mcp.server.mcpserver import MCPServer",
        *imports,
        "",
        f"server = MCPServer(name={json.dumps(spec.name)}, instructions={json.dumps(spec.summary)})",
        "",
    ]
    blocks = []
    for tool in spec.tools:
        impl = impls.get(tool.name)
        body = impl.body if impl else "raise NotImplementedError('no implementation generated')"
        local_imports = [ln.strip() for ln in (impl.imports if impl else []) if ln.strip()]
        body = "\n".join(local_imports + [textwrap.dedent(body).strip("\n")])
        blocks.append("\n".join([
            "",
            f"@server.tool(name={json.dumps(tool.name)})",
            signature_line(tool),
            docstring(tool),
            textwrap.indent(textwrap.dedent(body).strip("\n"), "    "),
            "",
        ]))
    footer = ["", 'if __name__ == "__main__":', '    server.run("stdio")', ""]
    return "\n".join(header) + "\n".join(blocks) + "\n".join(footer)


def impl_for(code: AdapterCode, tool: str) -> ToolImpl | None:
    return next((i for i in code.tools if i.tool == tool), None)
